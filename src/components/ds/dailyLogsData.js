/** Default Edit Daily logs layout — same order as the Daily Logs / symptoms page. */
export function getDefaultDailyLogsLayout() {
  return {
    visibleIds: DAILY_LOGS_SECTIONS.map((s) => s.id),
    hiddenIds: [],
  };
}

export const DAILY_LOGS_DEFAULT_LAYOUT = getDefaultDailyLogsLayout();

export function normalizeDailyLogsLayout(layout) {
  const allIds = DAILY_LOGS_SECTIONS.map((s) => s.id);
  if (!layout) {
    return { visibleIds: [...allIds], hiddenIds: [] };
  }
  const visibleIds = (layout.visibleIds || []).filter((id) => allIds.includes(id));
  const hiddenIds = (layout.hiddenIds || []).filter(
    (id) => allIds.includes(id) && !visibleIds.includes(id),
  );
  const missing = allIds.filter((id) => !visibleIds.includes(id) && !hiddenIds.includes(id));
  return {
    visibleIds: [...visibleIds, ...missing],
    hiddenIds,
  };
}

export function sectionsForLayout(
  layout,
  segment,
  selections,
  journal,
  bbtValue,
  extra = {},
) {
  const { visibleIds } = normalizeDailyLogsLayout(layout);
  const byId = Object.fromEntries(DAILY_LOGS_SECTIONS.map((s) => [s.id, s]));
  const ordered = visibleIds.map((id) => byId[id]).filter(Boolean);
  if (segment === "all") return ordered;
  return ordered.filter((section) => {
    if (section.emptyOnly && segment === "logged") return false;
    let logged = false;
    if (section.kind === "journal") logged = Boolean(String(journal || "").trim());
    else if (section.id === "bbt") logged = Boolean(bbtValue);
    else if (section.kind === "follicle") {
      logged =
        Boolean(extra.follicleSizes?.length) || Boolean(extra.endometrialThickness);
    } else if (section.kind === "blood") {
      logged = Object.keys(extra.bloodValues || {}).length > 0;
    } else if (section.id === "medication") {
      logged = Boolean(extra.medicationLogged);
    } else if (section.kind === "actions") {
      logged = false;
    } else {
      const selected = selections?.[section.id] || [];
      if (selected.length > 0) logged = true;
      else if (section.followups) {
        logged = section.followups.some(
          (f) => (selections?.[`${section.id}__${f.id}`] || []).length > 0,
        );
      } else {
        logged = (selections?.[`${section.id}__nested`] || []).length > 0;
      }
    }
    return segment === "logged" ? logged : !logged;
  });
}

